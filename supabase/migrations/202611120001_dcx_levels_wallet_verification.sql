-- DCX Mining: additive schema for wallet verification and level rewards
-- Existing mining/referral functions are intentionally not changed by this migration.

ALTER TABLE public."User"
  ADD COLUMN IF NOT EXISTS wallet_address text,
  ADD COLUMN IF NOT EXISTS wallet_verified boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS wallet_verified_at timestamptz,
  ADD COLUMN IF NOT EXISTS wallet_balance_dcx numeric(30,9) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS wallet_balance_checked_at timestamptz,
  ADD COLUMN IF NOT EXISTS level integer NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS wallet_verification_tx_hash text;

ALTER TABLE public."User"
  ADD CONSTRAINT user_level_range_check CHECK (level BETWEEN 1 AND 100);

CREATE UNIQUE INDEX IF NOT EXISTS user_wallet_address_unique_lower
  ON public."User" (lower(wallet_address))
  WHERE wallet_address IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS user_wallet_verification_tx_hash_unique
  ON public."User" (wallet_verification_tx_hash)
  WHERE wallet_verification_tx_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.dcx_level_rules (
  level integer PRIMARY KEY CHECK (level BETWEEN 1 AND 100),
  holding_required_dcx numeric(30,9) NOT NULL CHECK (holding_required_dcx >= 0),
  base_reward_dcx_per_day numeric(30,9) NOT NULL CHECK (base_reward_dcx_per_day >= 0),
  bonus_reward_dcx_per_day numeric(30,9) NOT NULL DEFAULT 0 CHECK (bonus_reward_dcx_per_day >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

