CREATE TABLE IF NOT EXISTS public.wallet_verification_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id bigint NOT NULL REFERENCES public."User"(telegram_id) ON DELETE CASCADE,
  wallet_address text NOT NULL,
  network text NOT NULL DEFAULT 'ton-mainnet' CHECK (network = 'ton-mainnet'),
  receiver_address text NOT NULL,
  amount_nano_ton bigint NOT NULL CHECK (amount_nano_ton = 70000000),
  transaction_hash text,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'verified', 'rejected')),
  verified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS wallet_verification_tx_hash_unique
  ON public.wallet_verification_payments (transaction_hash)
  WHERE transaction_hash IS NOT NULL;

CREATE INDEX IF NOT EXISTS wallet_verification_user_created_idx
  ON public.wallet_verification_payments (telegram_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.dcx_project_settings (
  setting_key text PRIMARY KEY,
  setting_value jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
